// P4405: an inline (linkonce_odr, comdat) function's proof shadow, never
// emitted, changes nothing in what is emitted for it and for the static
// function only its real code calls.  (Clang does not put g in f's comdat
// group, as gnu_gcc does; the test pins that the shadow changes nothing.)
// The real module, its IR and its object code, are exactly what they are
// without the shadows (-fno-contracts-prove-shadow) and with every evaluation
// ignore; -fno-contracts-prove-assume, so that nothing proven is assumed.
// Clang's shadows live in a proof module of their own, so the real code never
// sees them as callers or users.
//
// Mirror: gcc/testsuite/g++.dg/contracts/cpp26/p4405-shadow-same-code-comdat.C
// (GCC-907).

extern int sink(int);

__attribute__((noinline)) static int g(int x) { return sink(x) + 1; }

inline int f(int n) {
  contract_assert(n > 0);
  return g(n) * 2;
}

int (*use)(int) = f;

